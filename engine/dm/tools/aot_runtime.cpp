// Host runtime of the ahead-of-time recompiled AArch64 code (NX2Linux T3). The functions Remill lifted (aot_lift.py) call the `__remill_*` intrinsics defined here:
//   · guest memory: bounded regions, every access checked; an access outside them is an explicit error (address, size, read or write), never a host fault. Unaligned accesses are allowed, as on AArch64 normal memory.
//   · indirect calls and jumps (blr, br): the target must be the entry of an AOT function in aot_table (generated); any other target is counted as a fallback request and is an explicit error until the JIT
//     fallback (T4) takes it. A direct `bl` needs none of this: Remill lifted it into a call of sub_<address>, resolved at link time.
//   · errors leave the lifted code by longjmp (its frames hold no destructors), and aot_run reports them as text.
