// Guest memory regions. Guest threads read the list at every access while a service (MapMemory, SetHeapSize...) may add or remove regions: the list is a fixed array, an entry is written before the count is
// published, and a removed region only has its size set to 0 (its host memory is freed by aot_unmap_all, since a thread may still be inside an access to it).
enum { MAX_REGIONS = 512 };
struct Region { std::atomic<uint64_t> base, size; uint8_t *host; };
Region g_regions[MAX_REGIONS];
std::atomic<unsigned> g_nregions;
std::mutex g_regions_mu;
thread_local jmp_buf *g_jb;
thread_local char g_err[300];
thread_local State *g_state;   // the State of the run this host thread is executing: a service handler (a fiber switch) changes the thread pointers in it
thread_local bool g_exit_requested;   // a service handler asked this guest thread to end (svcExitThread): checked when the handler returns, so the unwinding stays in C
uint64_t g_stats[AOT_S_N];
enum { S_CALLS = AOT_S_CALLS, S_JUMPS = AOT_S_JUMPS, S_FALLBACK = AOT_S_FALLBACK, S_READS = AOT_S_READS, S_WRITES = AOT_S_WRITES, S_REGIONS = AOT_S_REGIONS };
inline void count(int i) { __atomic_fetch_add(&g_stats[i], 1, __ATOMIC_RELAXED); }   // guest threads run the lifted code at once
// The memory counters are bumped on every guest load and store by every thread: one shared atomic made them a cache-line fight (a game with 36 threads ran at a frame a second). Each thread counts in its own
// slot, aot_stat sums the slots. A slot is never freed (a thread that ended keeps its counts)
struct MemCounts { uint64_t reads, writes; };
std::mutex g_counts_mu; std::vector<MemCounts *> g_counts;
inline MemCounts &mem_counts() {
    static thread_local MemCounts *mine = nullptr;
    if (!mine) { mine = new MemCounts{0, 0}; std::lock_guard<std::mutex> g(g_counts_mu); g_counts.push_back(mine); }
    return *mine;
}
inline void count_read() { mem_counts().reads++; }
inline void count_write() { mem_counts().writes++; }

[[noreturn]] void fail(const char *fmt, ...) __attribute__((format(printf, 1, 2)));
[[noreturn]] void fail(const char *fmt, ...) {
    va_list ap; va_start(ap, fmt); vsnprintf(g_err, sizeof g_err, fmt, ap); va_end(ap);
    if (!g_jb) { fprintf(stderr, "[RED] aot: %s (outside aot_run)\n", g_err); abort(); }
    longjmp(*g_jb, 1);
}

uint8_t *guest(uint64_t a, uint64_t n, const char *what) {
    static thread_local unsigned last = 0;   // most accesses hit the region the previous one did (the stack, the heap): look there first
    if (last < MAX_REGIONS) { const Region &r = g_regions[last]; const uint64_t base = r.base, size = r.size; if (a >= base && n <= size && a - base <= size - n && size) return r.host + (a - base); }
    for (unsigned i = 0, e = g_nregions.load(std::memory_order_acquire); i < e; i++) {
        const Region &r = g_regions[i]; const uint64_t base = r.base, size = r.size;
        if (a >= base && n <= size && a - base <= size - n) { last = i; return r.host + (a - base); }
    }
    fail("guest %s of %llu bytes at %#llx is outside every mapped region", what, (unsigned long long)n, (unsigned long long)a);
}

