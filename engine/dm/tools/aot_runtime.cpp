// Floating-point exception flags. Remill's AArch64 semantics clear them, run the operation on the host FPU and read them back into FPSR; the masks are AArch64's FPSR bit positions
// (invalid 1, divide by zero 2, overflow 4, underflow 8, inexact 16, input denormal 128: x86 has no flag for that last one, so it is never reported)
static int fe_of(int32_t m) { return (m & 1 ? FE_INVALID : 0) | (m & 2 ? FE_DIVBYZERO : 0) | (m & 4 ? FE_OVERFLOW : 0) | (m & 8 ? FE_UNDERFLOW : 0) | (m & 16 ? FE_INEXACT : 0); }
int32_t __remill_fpu_exception_test(int32_t mask) {
    int e = fetestexcept(fe_of(mask));
    return (e & FE_INVALID ? 1 : 0) | (e & FE_DIVBYZERO ? 2 : 0) | (e & FE_OVERFLOW ? 4 : 0) | (e & FE_UNDERFLOW ? 8 : 0) | (e & FE_INEXACT ? 16 : 0);
}
void __remill_fpu_exception_clear(int32_t mask) { feclearexcept(fe_of(mask)); }
void __remill_fpu_exception_raise(int32_t mask) { feraiseexcept(fe_of(mask)); }

