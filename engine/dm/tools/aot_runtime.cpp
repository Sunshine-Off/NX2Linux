// Atomics. An exclusive store (stxr, stlxr) is a compare-and-swap against the value the exclusive load read (the Remill patch keeps it in MONITOR_VALUE), so it fails when another thread wrote
// the location in between. The access must be naturally aligned, as the hardware requires of an exclusive access: otherwise an explicit error.
