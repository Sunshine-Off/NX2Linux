// mrs xN, cntpct_el0: the virtual counter, 19.2 MHz as on the Switch (CNTFRQ_EL0), from the host's monotonic clock
extern "C" uint64_t __nx2_read_cntpct(void) {
    timespec ts; clock_gettime(CLOCK_MONOTONIC, &ts);
    return ((uint64_t)ts.tv_sec * 1000000000ull + (uint64_t)ts.tv_nsec) * 192ull / 10000ull;
}

