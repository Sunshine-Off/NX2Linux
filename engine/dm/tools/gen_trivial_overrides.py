#!/usr/bin/env python3
"""Generate horizon_trivial.py from the Mach host's HLE_FORCE table (engine/dm/host/hle_*.c): the entries whose body does nothing or returns a constant, with their reason strings.
Anything with logic is left to a hand-written port (horizon_fs.py, horizon_account.py ...). Usage: gen_trivial_overrides.py > horizon_trivial.py"""
import re, sys
from pathlib import Path

HOST = Path(__file__).resolve().parent.parent / 'host'
CONSTS = {'RES_OK': 0, 'RES_FAIL': 0x2A2, 'true': 1, 'false': 0, 'NULL': 0}
INT_TYPES = {'Result', 'int', 'unsigned', 'uint32_t', 'int32_t', 'uint8_t', 'bool', 'unsigned int', 'uint16_t', 'int8_t', 'uint64_t', 'int64_t', 'size_t', 'long', 'unsigned long', 'long long', 'unsigned long long'}
HEAD = re.compile(r'^HLE_FORCE(?:_BIG)?\(\s*"([^"]+)"\s*,\s*((?:"(?:[^"\\]|\\.)*"\s*)+),\s*([^,]+?)\s*,\s*(\w+)\s*,([^{]*?)\)\s*\{', re.M | re.S)


def strings(blob):
    return ''.join(re.findall(r'"((?:[^"\\]|\\.)*)"', blob)).replace('\\"', '"').replace('\\n', ' ')


def body_of(text, start):
    depth, i = 1, start
    while i < len(text) and depth:
        c = text[i]
        if c == '{': depth += 1
        elif c == '}': depth -= 1
        i += 1
    return text[start:i - 1]


def trivial(ret, body):
    b = re.sub(r'//[^\n]*|/\*.*?\*/', '', body, flags=re.S).strip()
    b = re.sub(r'\(void\)\s*\w+\s*;', '', b).strip()
    b = re.sub(r'\bDM_APPLET\([^)]*\)\s*;?', '', b).strip()
    if b == '': return ('void' if ret.strip() == 'void' else None, None)
    m = re.fullmatch(r'return\s+(\w+)\s*;', b)
    if m and ret.strip() in INT_TYPES:
        v = m.group(1)
        if v in CONSTS: return ('value', CONSTS[v])
        if re.fullmatch(r'-?\d+|0x[0-9a-fA-F]+', v): return ('value', int(v, 0))
    return (None, None)


# files whose entries replace calls to system services (hid, time, friends...): an entry with logic that is not ported by hand is answered 0 and counted, instead of letting the SDK call a service that is not there
SERVICE_FILES = ('hle_hid.c', 'hle_haptics.c', 'hle_touch.c', 'hle_misc.c', 'hle_friends.c', 'hle_net.c', 'hle_offline.c', 'hle_mii.c', 'hle_time.c', 'hle_swkbd.c', 'hle_account.c', 'hle_profile.c', 'hle_audio.c', 'hle_audren.c', 'hle_codec.c', 'hle_sdk16.c', 'hle_lifecycle.c', 'hle_fpslock.c', 'hle_cheats.c', 'hle_movie.c', 'hle_movie_avc.c')


def main():
    seen, out, stubbed = set(), [], []
    for f in sorted(HOST.glob('hle_*.c')):
        text = f.read_text(errors='replace')
        for m in HEAD.finditer(text):
            sym, why, ret, cname, args = m.group(1), strings(m.group(2)), m.group(3), m.group(4), m.group(5)
            kind, val = trivial(ret, body_of(text, m.end()))
            if sym in seen: continue
            seen.add(sym)
            if kind is None:
                if f.name in SERVICE_FILES: stubbed.append((sym, why, f.name))
                continue
            out.append((sym, kind, val, why, f.name))
    print('"""Generated by gen_trivial_overrides.py from the Mach host\'s HLE_FORCE entries that do nothing or return a constant (engine/dm/host/hle_*.c): %d of them. Do not edit; port entries with logic by hand."""' % len(out))
    print('# (symbol, value or None for a void function, reason, source file)')
    print('TRIVIAL = [')
    for sym, kind, val, why, src in out:
        print(f'    ({sym!r}, {val if kind == "value" else None!r}, {why!r}, {src!r}),')
    print(']')
    print('# entries with logic, in files that stand in for system services: answered 0 and counted until ported by hand (symbol, reason, source file)')
    print('STUBBED = [')
    for sym, why, src in stubbed:
        print(f'    ({sym!r}, {why!r}, {src!r}),')
    print(']')


if __name__ == '__main__': main()
