#!/usr/bin/env python3
"""The platform of every patch: common (useful to Apple and Linux), apple, or linux (patches/platforms.tsv).

  patch_platforms.py check     every patch of patches/series has one row with a valid class and a note, no row is left over, the lists
                               patches/series.<class> are current, and no patch depends on a patch of another class (see below)
  patch_platforms.py lists     write patches/series.common, series.apple and series.linux (the series order, one class each)
  patch_platforms.py summary   the count per class, and the common patches not yet forwarded upstream

A dependency is approximated by a shared file: a patch that changes a file an earlier patch changed depends on it. A patch may depend on
patches of its own class and on common ones. A dependency on another class is a violation, because the class could not be applied alone.
The violations that exist are listed in patches/platform-overlaps.tsv (patch, earlier patch, file): a new one fails the check, and so does
an entry that is no longer a violation. Files regenerated by tools (docs/env_switches.tsv) still count: they are a real ordering constraint.

The class is a review aid for splitting the series (plan rule 4) and for choosing what to send to seedds/nxnative. It does not change how patches apply."""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CLASSES = ('common', 'apple', 'linux')


def series(root=ROOT):
    return [l.strip() for l in (root / 'patches' / 'series').read_text().splitlines() if l.strip() and not l.startswith('#')]


def table(root=ROOT):
    rows = {}
    for n, line in enumerate((root / 'patches' / 'platforms.tsv').read_text().splitlines()[1:], 2):
        f = line.split('\t')
        if len(f) != 3:
            raise ValueError(f'platforms.tsv:{n}: expected file, class, note')
        rows[f[0]] = (f[1], f[2])
    return rows


def files_of(name, root=ROOT):
    return set(re.findall(r'^diff --git a/(\S+) b/', (root / 'patches' / name).read_text(errors='replace'), re.M))


def violations(root=ROOT):
    """{(patch, earlier patch, file)}: a patch whose file an earlier patch of another class, not common, also changed"""
    rows, seen, out = table(root), {}, set()
    for n in series(root):
        if n not in rows or not (root / 'patches' / n).is_file():
            continue
        for f in sorted(files_of(n, root)):
            for m in seen.get(f, []):
                if rows[m][0] not in (rows[n][0], 'common'):
                    out.add((n, m, f))
            seen.setdefault(f, []).append(n)
    return out


def known(root=ROOT):
    path = root / 'patches' / 'platform-overlaps.tsv'
    if not path.exists():
        return set()
    return {tuple(l.split('\t')) for l in path.read_text().splitlines()[1:] if l.strip()}


def list_text(cls, root=ROOT):
    rows = table(root)
    return ''.join(n + '\n' for n in series(root) if rows.get(n, ('',))[0] == cls)


def problems(root=ROOT):
    rows, out = table(root), []
    names = series(root)
    out += [f'{n}: no row in platforms.tsv' for n in names if n not in rows]
    out += [f'{n}: in platforms.tsv but not in the series' for n in rows if n not in names]
    out += [f'{n}: class {c!r} is not one of {", ".join(CLASSES)}' for n, (c, _) in rows.items() if c not in CLASSES]
    out += [f'{n}: empty note' for n, (_, note) in rows.items() if not note.strip()]
    if not out:
        for cls in CLASSES:
            f = root / 'patches' / f'series.{cls}'
            if not f.exists() or f.read_text() != list_text(cls, root):
                out.append(f'patches/series.{cls} is not current: run patch_platforms.py lists')
        have, now = known(root), violations(root)
        out += [f'{n} changes {f}, which the {rows[m][0]} patch {m} changed before: add a row to platform-overlaps.tsv or reclassify'
                for n, m, f in sorted(now - have)]
        out += [f'platform-overlaps.tsv: {n} / {m} / {f} is no longer an overlap: remove the row' for n, m, f in sorted(have - now)]
    return out


def status_of(name, root=ROOT):
    for line in (root / 'patches' / name).read_text(errors='replace').splitlines():
        if line.startswith('Upstream-Status:'):
            return line.split(':', 1)[1].strip()
    return '?'


def main(argv=None):
    cmd = (argv if argv is not None else sys.argv[1:])[:1]
    if cmd == ['check']:
        bad = problems()
        print('\n'.join(bad) if bad else f'patch platforms: ok. {len(table())} patches classified')
        return 1 if bad else 0
    if cmd == ['lists']:
        for cls in CLASSES:
            (ROOT / 'patches' / f'series.{cls}').write_text(list_text(cls))
        out = ['patch\tearlier patch\tfile'] + ['\t'.join(v) for v in sorted(violations())]
        (ROOT / 'patches' / 'platform-overlaps.tsv').write_text('\n'.join(out) + '\n')
        print('wrote patches/series.{common,apple,linux} and platform-overlaps.tsv (review the overlaps: each one is a patch that cannot be applied alone)')
        return 0
    if cmd == ['summary']:
        rows = table()
        for c in CLASSES:
            print(f'{c:7} {sum(1 for v in rows.values() if v[0] == c)}')
        print('common patches not yet forwarded upstream:')
        for n, (c, _) in rows.items():
            if c == 'common' and not status_of(n).startswith('forwarded'):
                print(f'  {n}  [{status_of(n)}]')
        return 0
    print(__doc__)
    return 2


if __name__ == '__main__':
    raise SystemExit(main())
